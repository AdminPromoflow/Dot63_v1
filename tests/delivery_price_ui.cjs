const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const unit = {textContent: ''};
const context = {console, URLSearchParams, FormData, window: {location: {search: '?sku=P&sku_variation=V'}}, document: {getElementById: () => unit}, alert: () => {}, location: {reload() {}}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('view/prices/prices/prices.js','utf8').replace('const prices = new Prices();', 'this.Prices = Prices;'), context);
vm.runInContext(fs.readFileSync('view/variations/varia/variations.js','utf8').replace('new Variations();', 'this.Variations = Variations;'), context);
(async () => {
 const app = Object.create(context.Prices.prototype);
 app.renderRows = () => {};
 app.drawRows([{price_id: 1, min_quantity: 10, max_quantity: 20, price: '3.25', delivery_time_days: 8, delivery_price: '12.50', delivery_price_type: 'percentage'}, {price_id: 2, delivery_price: null, delivery_price_type: null}]);
 assert.equal(app.rows[0].delivery_price, '12.50'); assert.equal(app.rows[1].delivery_price, '');
 assert.equal(app.rows[0].delivery_time_days, '8'); assert.equal(app.rows[1].delivery_time_days, '');
 const row = app.rows[0];
 const select = {dataset: {id:'1'}, value:'amount', closest: () => ({querySelector: () => unit})};
 app.handleListInput({target: {closest: selector => selector === '.delivery-type' ? select : null}});
 assert.equal(unit.textContent,'£ (GBP)'); assert.equal(row.delivery_price_type,'amount');
 app.addRow(); assert.equal(app.rows[0].delivery_price,'12.50'); assert.equal(app.rows[2].delivery_price,'');
 app.form = {reportValidity: () => true}; app.getSelectedDisplayIn = () => 'prices';
 const fields = {'.delivery-days':[{value:'8'}],'.remove':[{dataset:{id:'1'}}],'.min-input':[{value:'10'}],'.max-input':[{value:'20'}],'.price-input':[{value:'3.25'}],'.delivery-input':[{value:'12.50'}],'.delivery-type':[{value:'amount'}]};
 app.list={querySelectorAll: selector => fields[selector]};
 let payload; app.makeRequest=async (url,data) => {payload=data; return {success:true};};
 await app.save(); assert.equal(payload.delivery_time_days[0], '8'); assert.equal(payload.delivery_price[0],'12.50'); assert.equal(payload.delivery_price_type[0],'amount');
 const variation=Object.create(context.Variations.prototype);
 Object.assign(variation,{deliveryTimeInput:{value:'10',reportValidity:()=>true},deliveryPriceInput:{value:'2.50', reportValidity:()=>true},deliveryPriceType:{value:'amount'},nameInput:{value:'Test'},readSkuParamsFromUrl:()=>({skuProduct:'P',skuVariation:'V'})});
 variation.updateDeliveryUnit(); assert.equal(unit.textContent,'£ (GBP)');
 variation.makeRequest=async (url,data)=> {payload=data; return {success:true};};
 assert.equal(await variation.saveVariationDetails(false),true);
 assert.equal(payload.get('delivery_time_days'),'10'); assert.equal(payload.get('delivery_price'),'2.50'); assert.equal(payload.get('delivery_price_type'),'amount');
 variation.deliveryPriceInput.value=''; await variation.saveVariationDetails(false); assert.equal(payload.get('delivery_price'),'');
 console.log('Delivery UI: loading, row state, unit switching, payloads and clearing passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
